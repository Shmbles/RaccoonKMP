/**
 * Tema principal de Compose Multiplatform para el juego.
 * Aplica la paleta estilizada y la tipografía con sombra para lograr el aspecto visual de juego de mesa casual.
 */
@Composable
fun RaccoonTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    val colorScheme = LightColorScheme

